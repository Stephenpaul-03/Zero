import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createContentStore } from '../server/store.mjs';
test('nested navigation and file reordering preserve bytes even when imported filenames match', async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'zero-order-'));
 t.after(async()=>{assert.ok(path.resolve(root).startsWith(path.resolve(os.tmpdir())+path.sep));await fs.rm(root,{recursive:true,force:true})});
 await fs.mkdir(path.join(root,'content/files'),{recursive:true});
 const catalog={schemaVersion:2,categories:[{id:'languages',kind:'learn',title:'Programming Languages',order:0}],collections:[{id:'python',kind:'learn',slug:'python',title:'Python',description:'',listed:true,order:0,tags:[],categoryId:'languages',groups:[{id:'basics',title:'Basics',slug:'basics',order:0},{id:'practical',title:'Practical',slug:'practical',order:0,parentId:'basics'}]}],documents:[],assets:[]};
 await fs.writeFile(path.join(root,'content/catalog.json'),JSON.stringify(catalog,null,2)+'\n');
 const store=createContentStore(root);const state=await store.load();
 const imports=[{name:'notes.md',title:'First',slug:'first',source:'# First\n\nExact first contents.',collectionId:'python',groupId:'practical'},{name:'notes.md',title:'Second',slug:'second',source:'# Second\n\nExact second contents.',collectionId:'python',groupId:'practical'}];
 const imported=await store.apply({...state,imports});
 const [first,second]=imported.catalog.documents;
 assert.match(first.file,/programming-languages\/python\/basics\/practical\/01-notes\.md$/);
 assert.equal(first.slug,'basics/practical/first');
 const reordered=structuredClone(imported.catalog);reordered.documents[0].order=1;reordered.documents[1].order=0;
 const saved=await store.apply({catalog:reordered,revision:imported.revision,imports:[]});
 assert.equal((await store.read(first.id)).source,imports[0].source);assert.equal((await store.read(second.id)).source,imports[1].source);
 assert.match(saved.catalog.documents.find(doc=>doc.id===first.id).file,/02-notes\.md$/);
 assert.match(saved.catalog.documents.find(doc=>doc.id===second.id).file,/01-notes\.md$/);
 const navigation=JSON.parse(await fs.readFile(path.join(root,'content/navigation.json'),'utf8'));
 assert.deepEqual(navigation.sections.learn[0].menus[0].sections[0].children[0].documents.map(doc=>doc.title),['Second','First']);
 const cycle=structuredClone(saved.catalog);cycle.collections[0].groups[0].parentId='practical';
 await assert.rejects(store.apply({catalog:cycle,revision:saved.revision,imports:[]}),/cycle/);
 assert.equal((await store.load()).revision,saved.revision);
});
